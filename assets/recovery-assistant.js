// Recovery suggestion UI, registered once on the persistent workspace.
// No API keys, model hosting, or remote requests are required.
import {buildOfflineDraft, validateSafeDraft, sensitiveRecoveryContext} from './recovery-local.js';

export async function reportBrowserModelStatus(){
 const el=document.querySelector('#recovery-browser-ai-status');if(!el)return;
 const model=window.LanguageModel;
 if(!model||typeof model.create!=='function'){
  el.textContent='This browser does not support on-device AI. Quick Draft works offline without downloads or an API key.';
  return;
 }
 try{
  const status=typeof model.availability==='function'?await model.availability():'unknown';
  if(!el.isConnected)return;
  el.textContent=status==='available'
   ?'On-device Browser AI is ready; character evidence stays in your browser.'
   :status==='downloadable'||status==='downloading'
    ?'This browser can use on-device AI, but may need to download a model. Only clicking Browser AI starts that download.'
    :status==='unavailable'
     ?'On-device AI is unavailable on this device. Quick Draft still works without a model.'
     :'On-device AI may be supported here; generating a draft may require a model download.';
 }catch{if(el.isConnected)el.textContent='Could not check browser AI availability. Quick Draft works offline.';}
}

export function wireLocalRecovery(host,{state,getMessages,promptForField,renderSuggestions,applyDraft}){
 if(host.dataset.localRecoveryWired)return;
 host.dataset.localRecoveryWired='1';
 const message=(key,text,bad=false)=>{
  const label=host.querySelector('[data-local-status="'+key+'"]');
  if(label){label.textContent=text;label.className='recovery-status'+(bad?' is-error':'');}
 };
 const refresh=()=>{
  const existing=host.querySelector('#recovery-suggestions');
  if(existing)existing.outerHTML=renderSuggestions();
  void reportBrowserModelStatus();
 };
 const check=(key)=>{
  if(!['personality','scenario','example_dialogue'].includes(key))return 'Unsupported recovery field.';
  if(String(state.archiveEvidence?.[key]||'').trim())return 'An archived original exists. Automatic suggestions cannot replace it.';
  return '';
 };
 const browserDraft=(key)=>{
  const issue=check(key);if(issue){message(key,issue,true);return;}
  const model=window.LanguageModel;
  if(!model||typeof model.create!=='function'){
   message(key,'On-device AI is not available in this browser. Use Quick Draft or the optional external AI endpoint.',true);
   return;
  }
  const record=state.record,version=state.version;
  let promise;
  // Creation must begin directly from the user click: transient activation.
  try{promise=model.create();}
  catch(err){message(key,'Could not initialize browser AI: '+String(err?.message||err),true);return;}
  message(key,'Starting on-device AI (this may require a browser model download)…');
  void (async()=>{
   let session;
   try{
    session=await promise;
    const prompt=promptForField(key,getMessages()).slice(0,6500);
    const result=await session.prompt(prompt+'\nKeep all generated material non-explicit. Do not invent ages, relationships, or events unsupported by the archived evidence.');
    if(state.record!==record||state.version!==version)return;
    const draft=String(result||'').trim().replace(/^\x60{3}(?:text)?\s*/,'').replace(/\s*\x60{3}$/,'').slice(0,12000);
    const review=validateSafeDraft(key,draft,state.archiveEvidence);
    if(!review.ok)throw Error(review.reason);
    state.drafts[key]={text:draft,method:'browser-ai',reason:'Generated by the browser language model from the archived evidence. A proposed reconstruction, not the original wording.'};
    refresh();
    message(key,'Browser AI draft ready. Review it before accepting.');
   }catch(err){
    if(state.record===record)message(key,'Browser AI failed: '+String(err?.message||err)+'. Quick Draft works without the model.',true);
   }finally{try{session?.destroy?.();}catch{}}
  })();
 };
 host.addEventListener('click',event=>{
  const target=event.target;
  const quick=target.closest('[data-suggest-quick]');
  if(quick){
   const key=quick.dataset.suggestQuick,issue=check(key);
   if(issue){message(key,issue,true);return;}
   const draft=buildOfflineDraft(key,state.archiveEvidence,{messages:getMessages()});
   if(!draft.text){message(key,draft.reason||'Not enough archived evidence.',true);return;}
   state.drafts[key]=draft;refresh();
   message(key,'Quick Draft ready. This is a guided scaffold, not generative AI or an original archived field.');
   return;
  }
  const browser=target.closest('[data-suggest-browser]');
  if(browser){browserDraft(browser.dataset.suggestBrowser);return;}
  const accept=target.closest('[data-draft-apply]');
  if(accept){
   const key=accept.dataset.draftApply,source=state.drafts[key],issue=check(key);
   if(issue){message(key,issue,true);return;}
   if(!source)return;
   const box=host.querySelector('[data-draft-edit="'+key+'"]');
   const text=String(box?.value??source.text).trim();
   const review=validateSafeDraft(key,text,state.archiveEvidence);
   if(!review.ok){message(key,review.reason,true);return;}
   if(String(state.editor[key]||'').trim()&&!window.confirm('Replace your current field text with this draft?'))return;
   const edited=text!==source.text;
   applyDraft(key,text,source,edited);
   delete state.drafts[key];refresh();
   return;
  }
  const discard=target.closest('[data-draft-dismiss]');
  if(discard){delete state.drafts[discard.dataset.draftDismiss];refresh();}
 });
 void reportBrowserModelStatus();
}
